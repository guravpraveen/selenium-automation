DROP TABLE IF EXISTS PAYMENT_AUDIT;
DROP TABLE IF EXISTS PAYMENTS;
DROP TABLE IF EXISTS LIQUIDITY_POSITIONS;
DROP SEQUENCE IF EXISTS PAYMENT_SEQ;
CREATE SEQUENCE PAYMENT_SEQ START WITH 1000;
CREATE TABLE PAYMENTS (
    PAYMENT_ID     NUMBER PRIMARY KEY,
    TRN_REF        VARCHAR2(16) NOT NULL,
    UETR           VARCHAR2(36) NOT NULL,
    MSG_TYPE       VARCHAR2(20) NOT NULL,
    SCHEME         VARCHAR2(10) NOT NULL,
    SENDER_BIC     VARCHAR2(11) NOT NULL,
    RECEIVER_BIC   VARCHAR2(11) NOT NULL,
    CCY            VARCHAR2(3) NOT NULL,
    AMOUNT         NUMBER(18,3) NOT NULL,
    VALUE_DATE     DATE NOT NULL,
    STATUS         VARCHAR2(20) NOT NULL,
    CREATED_AT     TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE PAYMENT_AUDIT (
    AUDIT_ID    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PAYMENT_ID  NUMBER NOT NULL,
    OLD_STATUS  VARCHAR2(20),
    NEW_STATUS  VARCHAR2(20),
    CHANGED_AT  TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE LIQUIDITY_POSITIONS (
    ACCOUNT_NO     VARCHAR2(34) PRIMARY KEY,
    BIC            VARCHAR2(11) NOT NULL,
    CCY            VARCHAR2(3) NOT NULL,
    OPENING_BAL    NUMBER(18,3) NOT NULL,
    CURRENT_BAL    NUMBER(18,3) NOT NULL,
    THRESHOLD      NUMBER(18,3) NOT NULL
);
